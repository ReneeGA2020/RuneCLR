#!/bin/bash
# Run only the owned probe apps in a dedicated simulator, then shut it down.
set -euo pipefail
REPRO=${1:?Pass the directory generated by ios-r2r-repro.py}
CYCLES=${PROBE_CYCLES:-20}
LOGS="$REPRO/run-$(date -u +%Y%m%dT%H%M%SZ)"
mkdir -p "$LOGS"
SIM=$(xcrun simctl create RuneCLR-R2R-Investigation com.apple.CoreSimulator.SimDeviceType.iPhone-17 com.apple.CoreSimulator.SimRuntime.iOS-27-0)
echo "$SIM" > "$LOGS/simulator.uuid"
trap 'xcrun simctl shutdown "$SIM" > "$LOGS/shutdown.log" 2>&1 || true' EXIT
xcrun simctl boot "$SIM"
xcrun simctl bootstatus "$SIM" -b > "$LOGS/boot.log" 2>&1
for LANE in r2r il; do
    xcrun simctl install "$SIM" "$REPRO/$LANE/Probe.app"
done
for CASE in r2r:collect r2r:retain r2r:unload il:collect; do
    LANE=${CASE%%:*}
    MODE=${CASE#*:}
    SIMCTL_CHILD_PROBE_MODE=$MODE SIMCTL_CHILD_PROBE_CYCLES=$CYCLES \
        xcrun simctl launch --console "$SIM" "org.runeclr.ios.r2r.probe.$LANE" \
        > "$LOGS/$LANE-$MODE.log" 2>&1
done
python3 - "$LOGS" "$CYCLES" <<'PY'
import json
from pathlib import Path
import re
import sys
logs, cycles = Path(sys.argv[1]), int(sys.argv[2])
results = {}
for path in sorted(logs.glob('*-*.log')):
    data = path.read_text(errors='replace')
    results[path.stem] = {
        'pass': f'PROBE_PASS cycles={cycles}' in data and 'RUNECLR_EXIT=0' in data,
        'returned': len(re.findall(r'CYCLE=\d+ RETURNED', data)),
        'collected': data.count('COLLECTED=True'),
        'assertion': 'Assert failure' in data,
    }
(logs / 'results.json').write_text(json.dumps(results, indent=2) + '\n')
print(json.dumps(results, indent=2))
if len(results) != 4 or not all(r['pass'] and r['returned'] == cycles for r in results.values()):
    sys.exit(1)
if any(r['collected'] != cycles for name, r in results.items() if name.endswith('collect')):
    sys.exit(1)
PY
